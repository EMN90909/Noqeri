// Browser WebGPU adapter. GPU algorithms are authored in .noqeri and compiled
// to WGSL; this module owns only OS device resources, bindings and lifecycle.
function requireGpu(provided) {
  const gpu = provided ?? globalThis.navigator?.gpu
  if (!gpu) throw new Error('WebGPU is unavailable. Use a secure-context browser with WebGPU support.')
  return gpu
}
async function getDevice(gpu) {
  const adapter = await gpu.requestAdapter()
  if (!adapter) throw new Error('No WebGPU adapter was returned by the browser.')
  const device = await adapter.requestDevice()
  if (!device) throw new Error('WebGPU adapter failed to create a device.')
  return device
}
async function checkedModule(device, code) {
  if (typeof code !== 'string' || !code.includes('fn noqeri_shade('))
    throw new TypeError('Expected WGSL generated by the Noqeri shader compiler.')
  const module = device.createShaderModule({code})
  const info = await module.getCompilationInfo()
  const errors = info.messages.filter(message => message.type === 'error')
  if (errors.length) throw new Error('Generated WGSL was rejected: ' + errors.map(x => x.message).join('; '))
  return module
}
function computeMetadata(wgsl) {
  if (typeof wgsl !== 'string') throw new TypeError('Compute WGSL must be text.')
  const workgroup = /@compute\s+@workgroup_size\((32|64|128|256)\)(?=\s|$)/.exec(wgsl)
  const input = /var<storage,\s*read>\s+input_pixels\s*:\s*array<(u32|f32|vec4<f32>)>/.exec(wgsl)
  const output = /var<storage,\s*read_write>\s+output_pixels\s*:\s*array<(u32|f32|vec4<f32>)>/.exec(wgsl)
  if (!workgroup || !input || !output || input[1] !== output[1])
    throw new TypeError('Expected a Noqeri compute shader with matching storage buffers and workgroup size.')
  return {workgroupSize: Number(workgroup[1]), elementType: input[1]}
}
function assertGpuLimits(device, bytes, groups, groupSize) {
  const limits = device.limits
  if (!limits || !Number.isSafeInteger(limits.maxStorageBufferBindingSize) ||
      !Number.isSafeInteger(limits.maxBufferSize) ||
      !Number.isSafeInteger(limits.maxComputeWorkgroupsPerDimension) ||
      !Number.isSafeInteger(limits.maxComputeInvocationsPerWorkgroup))
    throw new Error('WebGPU adapter is missing required hardware limits.')
  if (bytes > limits.maxStorageBufferBindingSize || bytes > limits.maxBufferSize)
    throw new RangeError('Input exceeds this GPU device storage buffer limit.')
  if (groups > limits.maxComputeWorkgroupsPerDimension ||
      groupSize > limits.maxComputeInvocationsPerWorkgroup)
    throw new RangeError('Input exceeds this GPU device compute workgroup limits.')
}
export async function runNoqeriCompute(wgsl, pixels, suppliedGpu = null) {
  if (!(pixels instanceof Uint32Array) && !(pixels instanceof Float32Array))
    throw new TypeError('Compute input must be a Uint32Array or Float32Array.')
  const {workgroupSize, elementType} = computeMetadata(wgsl)
  if ((elementType === 'u32' && !(pixels instanceof Uint32Array)) ||
      ((elementType === 'f32' || elementType === 'vec4<f32>') && !(pixels instanceof Float32Array)))
    throw new TypeError('Compute shader scalar type does not match input buffer type.')
  if (elementType === 'vec4<f32>' && pixels.length % 4)
    throw new RangeError('vec4 compute input must contain groups of four floats.')
  if (!pixels.length) return new pixels.constructor(0)
  if (pixels.byteLength > 64 * 1024 * 1024)
    throw new RangeError('Compute demo input is capped at 64 MiB.')
  const device = await getDevice(requireGpu(suppliedGpu))
  let source, result, readback, mapped = false
  try {
    const elements = elementType === 'vec4<f32>' ? pixels.length / 4 : pixels.length
    const groups = Math.ceil(elements / workgroupSize)
    assertGpuLimits(device, pixels.byteLength, groups, workgroupSize)
    const module = await checkedModule(device, wgsl)
    const pipeline = device.createComputePipeline({
      layout: 'auto', compute: {module, entryPoint: 'main'}
    })
    source = device.createBuffer({
      size: pixels.byteLength, usage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_DST
    })
    result = device.createBuffer({
      size: pixels.byteLength, usage: GPUBufferUsage.STORAGE | GPUBufferUsage.COPY_SRC
    })
    readback = device.createBuffer({
      size: pixels.byteLength, usage: GPUBufferUsage.MAP_READ | GPUBufferUsage.COPY_DST
    })
    device.queue.writeBuffer(source, 0, pixels)
    const bindGroup = device.createBindGroup({
      layout: pipeline.getBindGroupLayout(0),
      entries: [{binding: 0, resource: {buffer: source}}, {binding: 1, resource: {buffer: result}}]
    })
    const encoder = device.createCommandEncoder()
    const pass = encoder.beginComputePass()
    pass.setPipeline(pipeline)
    pass.setBindGroup(0, bindGroup)
    pass.dispatchWorkgroups(groups)
    pass.end()
    encoder.copyBufferToBuffer(result, 0, readback, 0, pixels.byteLength)
    device.queue.submit([encoder.finish()])
    await readback.mapAsync(GPUMapMode.READ)
    mapped = true
    const copy = readback.getMappedRange().slice(0)
    readback.unmap()
    mapped = false
    return new pixels.constructor(copy)
  } finally {
    if (mapped) readback?.unmap()
    readback?.destroy()
    result?.destroy()
    source?.destroy()
    device.destroy()
  }
}
function checkedTexture(source) {
  if (!source || !Number.isSafeInteger(source.width) || !Number.isSafeInteger(source.height) ||
      source.width < 1 || source.height < 1 || source.width > 8192 || source.height > 8192 ||
      source.width * source.height > 16_777_216 ||
      !(source.data instanceof Uint8Array) ||
      source.data.byteLength !== source.width * source.height * 4)
    throw new TypeError('Texture must contain bounded width, height, and tightly packed RGBA8 Uint8Array pixels.')
  return source
}
export async function renderNoqeriFragment(canvas, wgsl, suppliedGpu = null, textureSource = null) {
  if (!canvas?.getContext) throw new TypeError('A WebGPU canvas is required.')
  if (typeof wgsl !== 'string' || !wgsl.includes('@fragment'))
    throw new TypeError('Expected a Noqeri fragment WGSL shader.')
  const requiresTexture = /var\s+nq_texture\s*:\s*texture_2d<f32>\s*;/.test(wgsl)
  const inputTexture = requiresTexture ? checkedTexture(textureSource) : null
  if (!requiresTexture && textureSource !== null)
    throw new TypeError('Shader has no texture binding but a texture was provided.')
  const gpu = requireGpu(suppliedGpu)
  const device = await getDevice(gpu)
  let context, configured = false, gpuTexture
  try {
    context = canvas.getContext('webgpu')
    if (!context) throw new Error('Browser did not provide a WebGPU canvas context.')
    const format = gpu.getPreferredCanvasFormat()
    context.configure({device, format, alphaMode: 'opaque'})
    configured = true
    const fragment = await checkedModule(device, wgsl)
    const vertex = device.createShaderModule({code: [
      '@vertex fn fullscreen(@builtin(vertex_index) index: u32) -> @builtin(position) vec4<f32> {',
      '  let positions = array<vec2<f32>, 3>(',
      '    vec2<f32>(-1.0, -1.0), vec2<f32>(3.0, -1.0), vec2<f32>(-1.0, 3.0)',
      '  );',
      '  return vec4<f32>(positions[index], 0.0, 1.0);',
      '}'
    ].join('\n')})
    const pipeline = device.createRenderPipeline({
      layout: 'auto',
      vertex: {module: vertex, entryPoint: 'fullscreen'},
      fragment: {module: fragment, entryPoint: 'main', targets: [{format}]},
      primitive: {topology: 'triangle-list'}
    })
    let bindGroup = null
    if (inputTexture) {
      if (inputTexture.width > device.limits.maxTextureDimension2D ||
          inputTexture.height > device.limits.maxTextureDimension2D)
        throw new RangeError('Texture dimensions exceed device limits.')
      gpuTexture = device.createTexture({
        size: [inputTexture.width, inputTexture.height, 1],
        format: 'rgba8unorm', usage: GPUTextureUsage.TEXTURE_BINDING | GPUTextureUsage.COPY_DST
      })
      device.queue.writeTexture(
        {texture: gpuTexture}, inputTexture.data,
        {bytesPerRow: inputTexture.width * 4, rowsPerImage: inputTexture.height},
        [inputTexture.width, inputTexture.height, 1]
      )
      const sampler = device.createSampler({magFilter: 'linear', minFilter: 'linear'})
      bindGroup = device.createBindGroup({
        layout: pipeline.getBindGroupLayout(0),
        entries: [{binding: 0, resource: gpuTexture.createView()}, {binding: 1, resource: sampler}]
      })
    }
    const encoder = device.createCommandEncoder()
    const pass = encoder.beginRenderPass({
      colorAttachments: [{
        view: context.getCurrentTexture().createView(),
        clearValue: {r: 0, g: 0, b: 0, a: 1},
        loadOp: 'clear', storeOp: 'store'
      }]
    })
    pass.setPipeline(pipeline)
    if (bindGroup) pass.setBindGroup(0, bindGroup)
    pass.draw(3)
    pass.end()
    device.queue.submit([encoder.finish()])
    await device.queue.onSubmittedWorkDone()
    let disposed = false
    return () => {
      if (disposed) return
      disposed = true
      context.unconfigure()
      gpuTexture?.destroy()
      device.destroy()
    }
  } catch (error) {
    if (configured) context.unconfigure()
    gpuTexture?.destroy()
    device.destroy()
    throw error
  }
}

function checkedClipVertices(vertices) {
  if (!(vertices instanceof Float32Array) || vertices.length === 0 ||
      vertices.length % 12 !== 0 || vertices.length > 393216)
    throw new TypeError('3D vertices must be bounded Float32Array triangle lists of clip-space vec4.')
  for(let i=0;i<vertices.length;i+=4) {
    const x=vertices[i],y=vertices[i+1],z=vertices[i+2],w=vertices[i+3]
    if(!Number.isFinite(x)||!Number.isFinite(y)||!Number.isFinite(z)||
       !Number.isFinite(w)||w<=0||w>1e6||
       Math.abs(x)>1e6||Math.abs(y)>1e6||z<0||z>w)
      throw new RangeError('Non-finite or unsafe homogeneous vertex coordinate at '+(i/4))
  }
  return vertices
}

// One-frame mesh renderer with GPU hardware depth testing. This is a narrow
// WebGPU bridge; the vertex and fragment algorithms are compiled from Noqeri.
// Input positions are already transformed to homogeneous clip space. No
// native GPU drivers, arbitrary vertex formats, or OS presentation is implied.
export async function renderNoqeriMesh3D(canvas, vertexWgsl, fragmentWgsl, positions, suppliedGpu = null) {
  if(!canvas?.getContext || !Number.isSafeInteger(canvas.width) ||
     !Number.isSafeInteger(canvas.height) ||
     canvas.width<1 || canvas.height<1 || canvas.width>4096 || canvas.height>4096)
    throw new TypeError('3D canvas dimensions must be between 1 and 4096.')
  if(typeof vertexWgsl!=='string' || !vertexWgsl.includes('@vertex') ||
     !vertexWgsl.includes('@builtin(position)') ||
     typeof fragmentWgsl!=='string' || !fragmentWgsl.includes('@fragment'))
    throw new TypeError('Expected Noqeri-generated vertex and fragment WGSL.')
  if(!(positions instanceof Float32Array))
    throw new TypeError('3D mesh positions must be Float32Array.')
  // Snapshot caller storage before validating, so a shared/mutable input
  // cannot change between GPU validation and queue.writeBuffer.
  const vertices=checkedClipVertices(new Float32Array(positions))
  const gpu=requireGpu(suppliedGpu)
  const device=await getDevice(gpu)
  let context,configured=false,vertexBuffer,depthTexture
  try {
    if(!device.limits || !Number.isSafeInteger(device.limits.maxTextureDimension2D) ||
       !Number.isSafeInteger(device.limits.maxBufferSize) ||
       canvas.width>device.limits.maxTextureDimension2D ||
       canvas.height>device.limits.maxTextureDimension2D ||
       vertices.byteLength>device.limits.maxBufferSize)
      throw new RangeError('3D resource exceeds WebGPU hardware limits.')
    context=canvas.getContext('webgpu')
    if(!context)throw new Error('Browser did not provide a WebGPU 3D canvas context.')
    const format=gpu.getPreferredCanvasFormat()
    context.configure({device,format,alphaMode:'opaque'})
    configured=true
    const vertex=await checkedModule(device,vertexWgsl)
    const fragment=await checkedModule(device,fragmentWgsl)
    const pipeline=device.createRenderPipeline({
      layout:'auto',
      vertex:{module:vertex,entryPoint:'main',buffers:[{
        arrayStride:16,stepMode:'vertex',
        attributes:[{shaderLocation:0,offset:0,format:'float32x4'}]
      }]},
      fragment:{module:fragment,entryPoint:'main',targets:[{format}]},
      primitive:{topology:'triangle-list',cullMode:'none'},
      depthStencil:{format:'depth24plus',depthWriteEnabled:true,depthCompare:'less'}
    })
    vertexBuffer=device.createBuffer({
      size:vertices.byteLength,usage:GPUBufferUsage.VERTEX|GPUBufferUsage.COPY_DST
    })
    device.queue.writeBuffer(vertexBuffer,0,vertices)
    depthTexture=device.createTexture({
      size:[canvas.width,canvas.height,1],
      format:'depth24plus',usage:GPUTextureUsage.RENDER_ATTACHMENT
    })
    const encoder=device.createCommandEncoder()
    const pass=encoder.beginRenderPass({
      colorAttachments:[{
        view:context.getCurrentTexture().createView(),
        clearValue:{r:0.05,g:0.05,b:0.07,a:1},
        loadOp:'clear',storeOp:'store'
      }],
      depthStencilAttachment:{
        view:depthTexture.createView(),
        depthClearValue:1,depthLoadOp:'clear',depthStoreOp:'store'
      }
    })
    pass.setPipeline(pipeline)
    pass.setVertexBuffer(0,vertexBuffer)
    pass.draw(vertices.length/4)
    pass.end()
    device.queue.submit([encoder.finish()])
    await device.queue.onSubmittedWorkDone()
    let disposed=false
    return ()=>{
      if(disposed)return
      disposed=true
      context.unconfigure()
      depthTexture.destroy()
      vertexBuffer.destroy()
      device.destroy()
    }
  }catch(error) {
    if(configured)context.unconfigure()
    depthTexture?.destroy()
    vertexBuffer?.destroy()
    device.destroy()
    throw error
  }
}
